// DEVELOPMENT TOOL - not part of the compiler and not the server.
//
// Runs the real C++ pipeline (analyze()) and writes its result in the frontend
// data contract (docs/frontend-contract.md) using the same serializer as the
// HTTP server (src/output/json_writer). It produces:
//   * the captured example outputs the web UI uses in offline (fixture) mode;
//   * on request, the JSON for any one source file.
// Nothing here is hand-written or simulated: every token, node and diagnostic
// comes from analyze().
//
//   export_fixtures --fixtures-dir DIR     write DIR/fixtures.js and DIR/fixtures-stress.js
//   export_fixtures --file SRC [--out OUT] write one response as JSON (stdout by default)

